#!/usr/bin/env python3
"""Generate COM vtable tables (d3d9_vtables.inc, d3d8_vtables.inc) from DXVK's
native DirectX headers.

usage: gen_vtables.py HEADER OUTPUT [Interface ...]

Each DECLARE_INTERFACE_ block lists the complete vtable (IUnknown methods
included) in slot order, which is exactly what the 32-bit game expects.
"""
import re
import sys

WANT = [
    "IDirect3D9", "IDirect3DDevice9", "IDirect3DVolume9", "IDirect3DSwapChain9",
    "IDirect3DSurface9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9",
    "IDirect3DTexture9", "IDirect3DCubeTexture9", "IDirect3DVolumeTexture9",
    "IDirect3DVertexDeclaration9", "IDirect3DVertexShader9", "IDirect3DPixelShader9",
    "IDirect3DStateBlock9", "IDirect3DQuery9",
]


D3D8 = [
    "IDirect3D8", "IDirect3DDevice8", "IDirect3DVolume8", "IDirect3DSwapChain8",
    "IDirect3DSurface8", "IDirect3DVertexBuffer8", "IDirect3DIndexBuffer8",
    "IDirect3DTexture8", "IDirect3DCubeTexture8", "IDirect3DVolumeTexture8",
]


def main(src, dst, want):
    text = open(src).read()
    out = ["// Generated by scripts/gen_vtables.py from DXVK's %s. Do not edit.\n" % src.split("/")[-1]]
    for iface in want:
        m = re.search(r"DECLARE_INTERFACE_\(%s\s*,\s*\w+\)\s*\{(.*?)\n\};" % iface, text, re.S)
        if not m:
            sys.exit("interface %s not found" % iface)
        methods = re.findall(r"STDMETHOD_?\(\s*(?:[\w\s\*]+?\s*,\s*)?(\w+)\s*\)", m.group(1))
        out.append("VTABLE_BEGIN(%s)\n" % iface)
        for name in methods:
            out.append("M(%s, %s)\n" % (iface, name))
        out.append("VTABLE_END(%s, %d)\n" % (iface, len(methods)))
    open(dst, "w").write("".join(out))


if __name__ == "__main__":
    want = sys.argv[3:] or (D3D8 if "d3d8" in sys.argv[1] else WANT)
    main(sys.argv[1], sys.argv[2], want)
